"""Generate the small SYNTHETIC corpus used by the Word2Vec demonstrations.

Why synthetic? Real resume corpora contain personal data and cannot be shipped
with a student project. Template sentences place related technologies in similar
contexts so that Word2Vec can learn rough clusters (languages, databases, cloud,
deep-learning frameworks...). The output is deterministic (fixed seed).

This corpus is far too small and artificial for production embeddings; it only
illustrates how CBOW and Skip-Gram learn from context windows.

Usage:  python backend/scripts/generate_corpus.py
"""

from __future__ import annotations

import random
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "data" / "corpus" / "tech_corpus.txt"

GROUPS = {
    "language": ["python", "java", "javascript", "typescript", "c++", "go", "kotlin", "rust"],
    "database": ["sql", "postgresql", "mysql", "mongodb", "redis", "sqlite"],
    "frontend": ["react", "angular", "vue", "html", "css", "tailwind"],
    "backend": ["flask", "django", "fastapi", "express", "node.js", "spring"],
    "cloud": ["aws", "azure", "gcp", "docker", "kubernetes", "terraform"],
    "dl": ["pytorch", "tensorflow", "keras", "transformers", "bert", "lstm"],
    "ml": ["scikit-learn", "pandas", "numpy", "xgboost", "matplotlib", "jupyter"],
    "nlp": ["nlp", "tokenization", "embeddings", "word2vec", "glove", "sentiment"],
}

TEMPLATES = {
    "language": [
        "wrote the service in {w} with clean code", "a {w} developer writes programs", "learned {w} programming language",
        "{w} code compiles and runs fast", "solved algorithm problems in {w}", "the {w} program uses functions and classes",
    ],
    "database": [
        "stored records in a {w} database", "wrote queries against {w} tables", "the {w} database indexes rows",
        "migrated data into {w} storage", "optimized {w} queries with indexes",
    ],
    "frontend": [
        "built the user interface with {w}", "styled web pages using {w}", "the {w} frontend renders components",
        "designed responsive pages in {w}", "{w} components update the browser view",
    ],
    "backend": [
        "built rest api endpoints with {w}", "the {w} server handles http requests", "deployed a {w} web backend",
        "wrote routes and middleware in {w}", "{w} backend connects to the database",
    ],
    "cloud": [
        "deployed containers on {w} infrastructure", "the {w} cluster scales the application", "configured {w} for cloud deployment",
        "automated infrastructure with {w}", "monitored services running on {w}",
    ],
    "dl": [
        "trained a neural network with {w}", "the {w} model learns from gpu training", "fine tuned a deep learning model using {w}",
        "{w} layers compute gradients with backpropagation", "built a deep neural network in {w}",
    ],
    "ml": [
        "analyzed the dataset with {w}", "trained a machine learning model using {w}", "explored data in {w} notebooks",
        "{w} helps with data analysis and features", "computed statistics on the data with {w}",
    ],
    "nlp": [
        "applied {w} to text documents", "the {w} step processes natural language", "used {w} for language understanding",
        "text classification relies on {w}", "{w} represents words and sentences as vectors",
    ],
}

# A few sentences for the classic analogy demo. With so little data the analogy
# may or may not work - which is itself a useful lesson.
ROYALTY = [
    "the king is a man who rules the kingdom", "the queen is a woman who rules the kingdom",
    "the prince is a young man of the royal family", "the princess is a young woman of the royal family",
    "a man and a woman walked to the palace", "the king and the queen live in the palace",
    "the man became king", "the woman became queen", "he is a man", "she is a woman",
]


def main(n_per_template: int = 12, seed: int = 42) -> None:
    rng = random.Random(seed)
    lines = [
        "# SYNTHETIC corpus generated by backend/scripts/generate_corpus.py (seed=42).",
        "# For Word2Vec demonstrations only. Not real resumes. Not suitable for production embeddings.",
    ]
    for group, words in GROUPS.items():
        for template in TEMPLATES[group]:
            for _ in range(n_per_template):
                w = rng.choice(words)
                other = rng.choice(words)
                sentence = template.format(w=w)
                if rng.random() < 0.4 and other != w:
                    sentence += f" and {other}"
                lines.append(sentence)
    for _ in range(25):
        lines.extend(ROYALTY)
    body = lines[2:]
    rng.shuffle(body)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines[:2] + body) + "\n", encoding="utf-8")
    print(f"Wrote {len(body)} sentences to {OUT}")


if __name__ == "__main__":
    main()
