"""Static word embeddings for the NLP Lab: Word2Vec (CBOW / Skip-Gram) and GloVe.

These are SYLLABUS DEMONSTRATIONS, not the main matching engine.

Word2Vec (Mikolov et al., 2013) learns vectors by predicting context:
  * CBOW (sg=0)      - predict the centre word from the surrounding context window
  * Skip-Gram (sg=1) - predict surrounding words from the centre word
We train on a small, clearly documented synthetic corpus
(data/corpus/tech_corpus.txt, generated by backend/scripts/generate_corpus.py).
A corpus this small CANNOT produce production-quality embeddings; neighbours
and analogies will be noisy.

GloVe (Pennington et al., 2014) factorises a global word-word co-occurrence
matrix. We load PRE-TRAINED Stanford GloVe vectors (glove-wiki-gigaword-50) via
gensim-data if they were downloaded beforehand. We never relabel Word2Vec
vectors as GloVe; if GloVe is missing the API says so and explains the setup.
"""

from __future__ import annotations

import logging
import os
import threading
from pathlib import Path

import numpy as np

from app.nlp.config import data_dir
from app.nlp.preprocessing.pipeline import TECH_TOKEN_RE

logger = logging.getLogger(__name__)

GLOVE_NAME = "glove-wiki-gigaword-50"

_lock = threading.Lock()
_w2v_models: dict[tuple[int, int, int], object] = {}
_glove = None
_glove_error: str | None = None
_glove_checked = False


class EmbeddingUnavailable(RuntimeError):
    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code
        self.message = message


def corpus_path() -> Path:
    return data_dir() / "corpus" / "tech_corpus.txt"


def load_corpus() -> list[list[str]]:
    path = corpus_path()
    if not path.exists():
        raise EmbeddingUnavailable("corpus_missing", f"Demo corpus not found at {path}. Run backend/scripts/generate_corpus.py")
    sentences = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        tokens = [t.lower() for t in TECH_TOKEN_RE.findall(line) if any(c.isalnum() for c in t)]
        if tokens:
            sentences.append(tokens)
    return sentences


def corpus_info() -> dict:
    sents = load_corpus()
    tokens = [t for s in sents for t in s]
    return {"sentences": len(sents), "tokens": len(tokens), "vocabulary": len(set(tokens)), "path": "data/corpus/tech_corpus.txt", "synthetic": True}


def _require_gensim():
    try:
        from gensim.models import Word2Vec  # noqa: F401
    except ImportError as exc:
        raise EmbeddingUnavailable("gensim_missing", "Gensim is not installed. Run: pip install gensim") from exc


def get_word2vec(sg: int, vector_size: int = 50, window: int = 4, epochs: int = 200):
    """Train (once, cached) a Word2Vec model on the demo corpus."""
    _require_gensim()
    from gensim.models import Word2Vec

    key = (sg, vector_size, window)
    with _lock:
        if key not in _w2v_models:
            sentences = load_corpus()
            # workers=1 + fixed seed => reproducible results across runs
            _w2v_models[key] = Word2Vec(
                sentences=sentences, vector_size=vector_size, window=window, min_count=2,
                sg=sg, epochs=epochs, seed=42, workers=1, negative=5,
            )
        return _w2v_models[key]


def get_glove():
    """Load pretrained GloVe vectors if available locally. Never downloads during a request."""
    global _glove, _glove_error, _glove_checked
    with _lock:
        if _glove is not None:
            return _glove
        if _glove_checked and _glove_error:
            raise EmbeddingUnavailable("glove_missing", _glove_error)
        _glove_checked = True
        try:
            from gensim.models import KeyedVectors
        except ImportError:
            _glove_error = "Gensim is not installed. Run: pip install gensim"
            raise EmbeddingUnavailable("glove_missing", _glove_error) from None

        explicit = os.environ.get("GLOVE_PATH")
        candidates: list[Path] = []
        if explicit:
            candidates.append(Path(explicit))
        candidates.append(data_dir() / "models" / f"{GLOVE_NAME}.kv")  # written by download_models.py (fast load)
        gensim_home = Path(os.environ.get("GENSIM_DATA_DIR", Path.home() / "gensim-data"))
        candidates.append(gensim_home / GLOVE_NAME / f"{GLOVE_NAME}.gz")
        for path in candidates:
            if path.exists():
                try:
                    if path.suffix in {".kv", ".model"}:
                        _glove = KeyedVectors.load(str(path))
                    else:
                        # GloVe text format without header (gensim>=4 supports no_header)
                        _glove = KeyedVectors.load_word2vec_format(str(path), binary=False, no_header=_has_no_header(path))
                    logger.info("Loaded GloVe vectors from %s", path)
                    return _glove
                except Exception as exc:
                    _glove_error = f"Failed to load GloVe from {path}: {type(exc).__name__}"
                    raise EmbeddingUnavailable("glove_missing", _glove_error) from exc
        _glove_error = (
            "Pretrained GloVe vectors are not downloaded. Run "
            "'python backend/scripts/download_models.py --glove' (downloads ~66 MB) and restart the backend."
        )
        raise EmbeddingUnavailable("glove_missing", _glove_error)


def _has_no_header(path: Path) -> bool:
    """gensim-data GloVe files include a word2vec header; raw Stanford files do not."""
    import gzip

    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rt", encoding="utf-8") as fh:
        first = fh.readline().split()
    return not (len(first) == 2 and all(p.isdigit() for p in first))


def _get_kv(model_name: str):
    if model_name == "word2vec-cbow":
        return get_word2vec(sg=0).wv
    if model_name == "word2vec-skipgram":
        return get_word2vec(sg=1).wv
    if model_name == "glove":
        return get_glove()
    raise EmbeddingUnavailable("unknown_model", f"Unknown embedding model '{model_name}'")


def model_status() -> dict:
    status = {"word2vec": {"available": True, "error": None}, "glove": {"available": False, "error": None}}
    try:
        _require_gensim()
        status["word2vec"]["corpus"] = corpus_info()
    except EmbeddingUnavailable as exc:
        status["word2vec"] = {"available": False, "error": exc.message}
    try:
        kv = get_glove()
        status["glove"] = {"available": True, "error": None, "vocabulary": len(kv.index_to_key), "dimension": kv.vector_size, "name": GLOVE_NAME}
    except EmbeddingUnavailable as exc:
        status["glove"] = {"available": False, "error": exc.message}
    return status


def word_vector_info(model_name: str, words: list[str], topn: int = 8) -> dict:
    kv = _get_kv(model_name)
    results = []
    for raw in words:
        w = raw.strip().lower()
        if not w:
            continue
        if w not in kv.key_to_index:
            results.append({"word": w, "in_vocabulary": False, "message": f"'{w}' is out of vocabulary (OOV) for this model."})
            continue
        vec = kv[w]
        results.append({
            "word": w,
            "in_vocabulary": True,
            "vector_preview": [round(float(x), 4) for x in vec[:10]],
            "dimension": int(vec.shape[0]),
            "neighbors": [{"word": n, "similarity": round(float(s), 4)} for n, s in kv.most_similar(w, topn=topn)],
        })
    pair_sims = []
    valid = [r["word"] for r in results if r.get("in_vocabulary")]
    for i in range(len(valid)):
        for j in range(i + 1, len(valid)):
            pair_sims.append({"a": valid[i], "b": valid[j], "similarity": round(float(kv.similarity(valid[i], valid[j])), 4)})
    return {"model": model_name, "vocabulary_size": len(kv.index_to_key), "dimension": kv.vector_size, "words": results, "pairwise": pair_sims}


def compare_cbow_skipgram(words: list[str], window: int = 4, vector_size: int = 50, topn: int = 6) -> dict:
    out = {"window": window, "vector_size": vector_size, "corpus": corpus_info(), "models": {}}
    for label, sg in (("cbow", 0), ("skipgram", 1)):
        model = get_word2vec(sg=sg, vector_size=vector_size, window=window)
        kv = model.wv
        entries = []
        for raw in words:
            w = raw.strip().lower()
            if w in kv.key_to_index:
                entries.append({"word": w, "neighbors": [{"word": n, "similarity": round(float(s), 4)} for n, s in kv.most_similar(w, topn=topn)]})
            else:
                entries.append({"word": w, "oov": True, "neighbors": []})
        out["models"][label] = {"vocabulary_size": len(kv.index_to_key), "words": entries}
    out["note"] = (
        "Trained on a small synthetic corpus; results illustrate the method only and differ between CBOW "
        "(averages context, smoother for frequent words) and Skip-Gram (predicts context, better for rare words)."
    )
    return out


def analogy(model_name: str, positive: list[str], negative: list[str], topn: int = 5) -> dict:
    """Vector arithmetic, e.g. king - man + woman ~ queen."""
    kv = _get_kv(model_name)
    pos = [w.strip().lower() for w in positive if w.strip()]
    neg = [w.strip().lower() for w in negative if w.strip()]
    oov = [w for w in pos + neg if w not in kv.key_to_index]
    if oov:
        return {"model": model_name, "ok": False, "oov": oov, "message": f"Out of vocabulary: {', '.join(oov)}", "results": []}
    results = kv.most_similar(positive=pos, negative=neg, topn=topn)
    return {
        "model": model_name,
        "ok": True,
        "expression": " + ".join(pos) + (" - " + " - ".join(neg) if neg else ""),
        "results": [{"word": w, "similarity": round(float(s), 4)} for w, s in results],
        "note": "Analogy quality depends on the model and its training data; small corpora rarely reproduce classic analogies.",
    }


def vectors_for(model_name: str, words: list[str]) -> tuple[list[str], np.ndarray, list[str]]:
    kv = _get_kv(model_name)
    kept, oov = [], []
    for raw in words:
        w = raw.strip().lower()
        (kept if w in kv.key_to_index else oov).append(w)
    if not kept:
        return [], np.zeros((0, kv.vector_size)), oov
    return kept, np.stack([kv[w] for w in kept]), oov
